import { fmt } from "@/lib/i18n";
import type { AppCopy } from "@/lib/i18n-app";
import { createClient } from "@/lib/supabase/server";

/**
 * The coordinator's ranked daily queue, read from the cohort.
 *
 * WHY THIS REPLACED A FIXTURE. This is the screen the brief names — "a Care
 * Coordinator dashboard sorted by urgency" — and it was rendering three
 * invented people while eighteen thousand scored senior-days sat in the
 * database. Every piece of model work was real and none of it was reachable
 * from the one page a reviewer opens first.
 *
 * SURFACED AND HELD COME FROM DIFFERENT PLACES, ON PURPOSE. The surfaced rows
 * are `alerts`: the model already applied the daily cap and the per-senior
 * cooldown when it wrote that table, so re-deriving the cut here would mean
 * two budget implementations that can disagree. The held rows are the rest of
 * that day's `risk_scores` — scored, ranked, and deliberately not shown. They
 * are the evidence the cap is doing something, which is why they are dimmed
 * rather than hidden.
 *
 * "TODAY" IS THE LAST DAY WITH DATA, not the system clock. The cohort covers
 * a fixed window; pointing at the real today would give a reviewer an empty
 * queue on a system that works.
 *
 * Every query runs as the signed-in coordinator through RLS, so "whose
 * seniors" is answered by the database rather than by a filter here that
 * could be left out.
 */

export type Level = "high" | "med" | "low";

export interface WorklistReason {
  code: string;
  text: string;
  contribution: number;
}

export interface WorklistRow {
  id: string;
  name: string;
  age: number;
  city: string;
  initials: string;
  score: number;
  level: Level;
  levelLabel: string;
  dueAt: string;
  reasons: WorklistReason[];
  nextStep: string;
  daysSinceContact: number;
  /** Null until a coordinator records one. Drives the verdict control. */
  verdict: string | null;
  alertId: number | null;
}

/**
 * A call that came down the phone line today and ran the whole script.
 *
 * WHY THIS IS SEPARATE FROM THE RANKED LIST. The ranking is computed once a
 * day under a hard alert budget, and that budget is the product. A check-in
 * that arrives afterwards has not been scored and must not quietly jump the
 * queue -- but it is also the senior's own voice, arriving after the model
 * had its say, and burying it until tomorrow's run would be the one thing a
 * coordinator would never forgive. So it is shown, beside the list rather
 * than inside it, and the coordinator decides.
 */
export interface TodayCheckin {
  seniorId: string;
  name: string;
  initials: string;
  /**
   * Answers worth a coordinator's attention, already worded. Empty when the
   * senior answered and nothing they said needs acting on -- which is still
   * shown, because it is the answer to "did my call go through".
   */
  concerns: string[];
}

export interface Worklist {
  state: "ok" | "empty";
  day: string;
  dayLabel: string;
  surfaced: WorklistRow[];
  held: WorklistRow[];
  /** Everyone scored that day, whether shown or not. */
  totalScored: number;
  /** Calls that came in today, after the ranking was computed. */
  answeredToday: TodayCheckin[];
}

function levelFor(score: number): Level {
  return score >= 0.6 ? "high" : score >= 0.35 ? "med" : "low";
}

function initialsFor(name: string): string {
  return name
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((p) => p[0]?.toUpperCase() ?? "")
    .join("");
}

/**
 * Reasons in the reader's language.
 *
 * Both sentences were generated by the explain layer and both passed the
 * never-diagnose gate, so picking between them here is a display choice, not
 * a translation. Falling back to English when `text_hi` is absent is
 * deliberate: a row written before the bilingual pass should read in the
 * wrong language rather than be blank.
 */
function parseReasons(raw: unknown, lang: string): WorklistReason[] {
  let value = raw;
  if (typeof value === "string") {
    try {
      value = JSON.parse(value);
    } catch {
      return [];
    }
  }
  if (!Array.isArray(value)) return [];
  return value
    .filter((r): r is Record<string, unknown> => !!r && typeof r === "object")
    .map((r) => ({
      code: String(r.code ?? ""),
      text: String((lang === "hi" && r.text_hi) || r.text || ""),
      contribution: Number(r.contribution ?? 0),
    }))
    .filter((r) => r.text);
}

/**
 * A suggested call slot, spread across the morning in rank order.
 *
 * Derived from the position in the queue, not stored: nothing in the data
 * says when a call is "due", and inventing a timestamp and presenting it as
 * recorded would be the kind of small lie that makes a reviewer doubt the
 * larger numbers. It is a suggestion the ordering implies, and the top of the
 * list is suggested first.
 */
function slotFor(rank: number, lang: string): string {
  const start = 9 * 60 + 20;
  const minutes = start + rank * 25;
  const d = new Date(Date.UTC(2000, 0, 1, Math.floor(minutes / 60), minutes % 60));
  return new Intl.DateTimeFormat(lang === "hi" ? "hi-IN" : "en-IN", {
    hour: "numeric",
    minute: "2-digit",
    timeZone: "UTC",
  }).format(d);
}

export async function loadWorklist(t: AppCopy, lang: string): Promise<Worklist> {
  const supabase = await createClient();

  const empty: Worklist = {
    state: "empty",
    day: "",
    dayLabel: "",
    surfaced: [],
    held: [],
    totalScored: 0,
    answeredToday: [],
  };

  // In parallel, because neither needs the other. The latest scored day is
  // the same across the cohort, so it does not have to wait for the caseload
  // to come back first — and this page is three round trips deep already.
  const [assignmentRes, lastDayRes] = await Promise.all([
    supabase.from("care_assignments").select("senior_id"),
    supabase
      .from("risk_scores")
      .select("scored_on")
      .order("scored_on", { ascending: false })
      .limit(1)
      .maybeSingle(),
  ]);

  const ids = (assignmentRes.data ?? []).map((a) => a.senior_id);
  if (!ids.length) return empty;

  const day = lastDayRes.data?.scored_on;
  if (!day) return empty;

  const contactFloor = new Date(new Date(`${day}T00:00:00Z`).getTime() - 14 * 86_400_000)
    .toISOString()
    .slice(0, 10);

  const [seniors, scores, alerts, contacts] = await Promise.all([
    supabase.from("seniors").select("id, display_name, age, city").in("id", ids),
    supabase
      .from("risk_scores")
      .select("senior_id, score, reasons")
      .in("senior_id", ids)
      .eq("scored_on", day),
    supabase
      .from("alerts")
      .select("id, senior_id, score, rank_in_day, reason_text, next_step, next_step_hi, status")
      .in("senior_id", ids)
      .eq("raised_on", day)
      .order("rank_in_day"),
    // Last time anyone actually reached this senior, for the tie-break the
    // ranking already uses: if two people look equally concerning, call the
    // one nobody has spoken to.
    //
    // Bounded to a fortnight. Unbounded, this pulled every answered call for
    // every senior on the caseload — around a thousand rows to compute one
    // integer each. Anyone not reached inside two weeks is already past every
    // threshold that uses this number, so the extra history changes nothing
    // and the cap is the difference between a page and a wait.
    supabase
      .from("call_notes")
      .select("senior_id, called_on, reached")
      .in("senior_id", ids)
      .eq("reached", true)
      .gte("called_on", contactFloor)
      .order("called_on", { ascending: false }),
  ]);

  // Calls that ran the CURRENT six-question script. `fall_code` is only
  // written by a call that asked all six, so its presence distinguishes a
  // real call today from the cohort's historical rows, which carry the three
  // the table used to have room for. A missed call has none of them, which is
  // right: it carries no answers to report.
  const todayCalls = await supabase
    .from("checkins")
    .select("senior_id, feeling_code, pain_code, meds_taken, sleep_code, appetite_code, fall_code")
    .in("senior_id", ids)
    .eq("checked_on", day)
    .eq("answered", true)
    .not("fall_code", "is", null);

  const seniorById = new Map((seniors.data ?? []).map((s) => [s.id, s]));
  const scoreById = new Map((scores.data ?? []).map((s) => [s.senior_id, s]));

  const lastReached = new Map<string, string>();
  for (const c of contacts.data ?? []) {
    if (!lastReached.has(c.senior_id)) lastReached.set(c.senior_id, c.called_on);
  }

  const dayMs = new Date(`${day}T00:00:00Z`).getTime();
  const sinceContact = (seniorId: string) => {
    const last = lastReached.get(seniorId);
    // Nothing inside the window means "longer ago than we looked", which is
    // what 99 has always meant here.
    if (!last) return 99;
    return Math.max(
      0,
      Math.round((dayMs - new Date(`${last}T00:00:00Z`).getTime()) / 86_400_000),
    );
  };

  const alertedIds = new Set<string>();

  const build = (
    seniorId: string,
    score: number,
    reasons: WorklistReason[],
    rank: number,
    nextStep: string,
    verdict: string | null,
    alertId: number | null,
  ): WorklistRow | null => {
    const s = seniorById.get(seniorId);
    if (!s) return null;
    const level = levelFor(score);
    return {
      id: seniorId,
      name: s.display_name,
      age: s.age ?? 0,
      city: s.city ?? "",
      initials: initialsFor(s.display_name),
      score,
      level,
      levelLabel: t.worklist.levels[level],
      dueAt: slotFor(rank, lang),
      reasons,
      nextStep,
      daysSinceContact: sinceContact(seniorId),
      verdict,
      alertId,
    };
  };

  const surfaced: WorklistRow[] = [];
  (alerts.data ?? []).forEach((a, i) => {
    alertedIds.add(a.senior_id);
    const scoreRow = scoreById.get(a.senior_id);
    // Prefer the per-score reasons: they exist for every day, where the alert
    // carries only the single headline sentence.
    const reasons = parseReasons(scoreRow?.reasons, lang);
    const row = build(
      a.senior_id,
      Number(a.score ?? scoreRow?.score ?? 0),
      reasons.length
        ? reasons
        : [{ code: "alert", text: a.reason_text ?? "", contribution: Number(a.score ?? 0) }],
      i,
      (lang === "hi" && a.next_step_hi) || a.next_step || "",
      a.status && a.status !== "open" ? a.status : null,
      a.id ?? null,
    );
    if (row) surfaced.push(row);
  });

  const held: WorklistRow[] = (scores.data ?? [])
    .filter((s) => !alertedIds.has(s.senior_id))
    .map((s) => ({ row: s, score: Number(s.score) }))
    .sort((a, b) => b.score - a.score)
    .map(({ row, score }, i) =>
      build(
        row.senior_id,
        score,
        parseReasons(row.reasons, lang),
        surfaced.length + i,
        "",
        null,
        null,
      ),
    )
    .filter((r): r is WorklistRow => r !== null);

  // Every call that came in is listed; only the answers worth ACTING on are
  // spelled out. An earlier version dropped a senior entirely when nothing
  // they said was concerning, which was wrong twice over: it made a
  // successful check-in indistinguishable from one that never arrived, and it
  // threw away the single most reassuring fact a coordinator can have, which
  // is that somebody picked up and said they were fine. Good news is still
  // news; it just does not get six red words.
  const answeredToday: TodayCheckin[] = (todayCalls.data ?? [])
    .map((c) => {
      const s = seniorById.get(c.senior_id);
      if (!s) return null;
      const concerns: string[] = [];
      if (c.feeling_code === 3) concerns.push(t.worklist.saidWorse);
      if (c.pain_code === 3) concerns.push(t.worklist.saidPain);
      if (c.meds_taken === false) concerns.push(t.worklist.saidMissedMeds);
      if (c.sleep_code === 3) concerns.push(t.worklist.saidSlept);
      if (c.appetite_code === 3) concerns.push(t.worklist.saidAte);
      // A near-fall counts. It is the only warning that arrives before
      // somebody is actually on the floor.
      if (c.fall_code === 3) concerns.push(t.worklist.saidFell);
      else if (c.fall_code === 2) concerns.push(t.worklist.saidNearlyFell);
      return {
        seniorId: c.senior_id,
        name: s.display_name,
        initials: initialsFor(s.display_name),
        concerns,
      };
    })
    .filter((x): x is TodayCheckin => x !== null);

  if (!surfaced.length && !held.length) return empty;

  const dayLabel = new Intl.DateTimeFormat(lang === "hi" ? "hi-IN" : "en-IN", {
    weekday: "long",
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(`${day}T00:00:00Z`));

  return {
    state: "ok",
    day,
    dayLabel: fmt(t.worklist.dateOn, { date: dayLabel }),
    surfaced,
    held,
    answeredToday,
    totalScored: (scores.data ?? []).length,
  };
}
