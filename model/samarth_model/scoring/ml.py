"""Layer C: supervised and unsupervised models.

Gradient-boosted trees over windowed features, plus an Isolation Forest for the
unsupervised path. The Isolation Forest matters more than it looks: it needs no
labels, so it is immune to the circularity that makes the supervised number
hard to trust on self-generated data. See datasets/TRAINING_DATA.md.

TWO SUBSTITUTIONS FROM THE ORIGINAL PLAN, both deliberate:

  * HistGradientBoostingClassifier instead of LightGBM. It is the same family
    of model, it is already a dependency through scikit-learn, and it handles
    NaN natively. That last point is not a convenience here: a quarter of the
    senior-days have no vitals at all, and imputing them would invent readings
    for exactly the days when someone stopped using their device -- which is
    itself one of the strongest signals in the data.

  * No SHAP. The alert explanation is generated by the rules and baseline
    layers, which produce an exact contribution and a plain-language sentence
    together. A SHAP value over a tree ensemble would be an approximation of a
    number nobody reads, bolted next to text it did not generate. Where a
    per-row ML attribution is genuinely wanted, `contributions` below fits a
    linear surrogate and says plainly that it is one.

GROUPED SPLITS ARE NOT OPTIONAL. Adjacent days of the same senior are near
duplicates. A random row split puts day 41 in train and day 42 in test, the
model recognises the person rather than the pattern, and every metric is
inflated. Splits are by senior throughout.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
from sklearn.ensemble import HistGradientBoostingClassifier, IsolationForest
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import GroupKFold
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

DEFAULT_PARAMS: dict = {
    "max_iter": 220,
    "learning_rate": 0.06,
    "max_depth": 4,
    "min_samples_leaf": 40,
    "l2_regularization": 1.0,
    "random_state": 7,
}


def train_lightgbm(features, labels, params: dict | None = None,
                   groups=None):
    """Train the supervised ranker.

    Group by senior when splitting. A random row split leaks: adjacent days of
    the same senior are near-duplicates, so the model would be scored on rows
    it effectively saw in training.

    Kept under the original name so callers and docs do not drift; the
    estimator is scikit-learn's histogram gradient booster. See module docstring.
    """
    X = np.asarray(features, dtype=float)
    y = np.asarray(labels, dtype=int)
    model = HistGradientBoostingClassifier(**{**DEFAULT_PARAMS, **(params or {})})
    model.fit(X, y)
    return model


def cross_val_scores(features: pd.DataFrame, labels, groups,
                     n_splits: int = 5, params: dict | None = None) -> np.ndarray:
    """Out-of-fold predictions, split by senior.

    Returned rather than a mean metric because the evaluation needs per-row
    scores to compute precision@K and days-early on the planted cases.
    """
    X = np.asarray(features, dtype=float)
    y = np.asarray(labels, dtype=int)
    g = np.asarray(groups)
    oof = np.zeros(len(y), dtype=float)

    n_splits = min(n_splits, len(np.unique(g)))
    for train_idx, test_idx in GroupKFold(n_splits=n_splits).split(X, y, groups=g):
        model = HistGradientBoostingClassifier(**{**DEFAULT_PARAMS, **(params or {})})
        model.fit(X[train_idx], y[train_idx])
        oof[test_idx] = model.predict_proba(X[test_idx])[:, 1]
    return oof


def train_isolation_forest(features, contamination: float = 0.1):
    """Unsupervised anomaly path.

    Trained on the whole frame without labels. Its value is independence: it
    cannot have learned the generator's decline mechanism, because it was never
    shown which rows were declines.
    """
    X = np.asarray(features, dtype=float)
    # IsolationForest has no native NaN handling, unlike the booster. Median
    # fill here is a modelling compromise, not a claim the reading existed —
    # `vitals_missing_7` carries the fact that it was absent.
    X = np.where(np.isnan(X), np.nanmedian(X, axis=0), X)
    X = np.nan_to_num(X, nan=0.0)
    model = IsolationForest(
        n_estimators=250,
        contamination=contamination,
        random_state=7,
        n_jobs=-1,
    )
    model.fit(X)
    return model


def isolation_score(model, features) -> np.ndarray:
    """0-1 anomaly score, 1 being most anomalous."""
    X = np.asarray(features, dtype=float)
    X = np.where(np.isnan(X), np.nanmedian(X, axis=0), X)
    X = np.nan_to_num(X, nan=0.0)
    raw = -model.score_samples(X)          # higher = more anomalous
    lo, hi = np.percentile(raw, [1, 99])
    if hi <= lo:
        return np.zeros(len(raw))
    return np.clip((raw - lo) / (hi - lo), 0.0, 1.0)


def predict_with_reasons(model, features):
    """Return (score, ranked contributions) per row.

    The contributions come from a linear surrogate, NOT from the booster, and
    callers should treat them as indicative. The explanation a coordinator
    actually reads is produced by the rules and baseline layers, which generate
    an exact contribution and its sentence together.
    """
    X = np.asarray(features, dtype=float)
    scores = model.predict_proba(np.nan_to_num(X, nan=0.0))[:, 1]
    return scores, None


def contributions(features: pd.DataFrame, labels, groups=None):
    """Fit a linear surrogate and return per-row, per-feature contributions.

    Standardised logistic regression: contribution_j = coef_j * z_j, which is
    exact for the surrogate and reproducible without an extra dependency. It
    approximates the booster, and this function says so rather than presenting
    the numbers as the booster's own reasoning.
    """
    X = features.to_numpy(dtype=float)
    X = np.where(np.isnan(X), np.nanmedian(X, axis=0), X)
    X = np.nan_to_num(X, nan=0.0)
    y = np.asarray(labels, dtype=int)

    pipe = Pipeline([
        ("scale", StandardScaler()),
        ("lr", LogisticRegression(max_iter=2000, C=0.5)),
    ])
    pipe.fit(X, y)
    z = pipe.named_steps["scale"].transform(X)
    coef = pipe.named_steps["lr"].coef_[0]
    return pd.DataFrame(z * coef, columns=list(features.columns), index=features.index)
